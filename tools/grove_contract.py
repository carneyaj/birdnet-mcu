"""Build the Grove model/label payload and C++ identity for the bundled model."""
import argparse
import hashlib
import json
from pathlib import Path

from label_blob import fnv1a, package
from species_profile import load_labels, render_profile


def digest(data):
    return hashlib.sha256(data).hexdigest()


def prepare(models, app, capture_elf, bundle):
    result = json.loads((models / "grove-contract.json").read_text())
    model = (models / "grove-ethosu.tflite").read_bytes()
    labels_data = (models / "labels.txt").read_bytes()
    if digest(model) != result["model_sha256"] or digest(labels_data) != result["labels_sha256"]:
        raise ValueError("Grove model or ordered labels differ from the packaged contract")
    labels = load_labels(labels_data)
    if len(labels) != result["classes"]:
        raise ValueError("Ordered labels differ from the model output count")
    profile = render_profile(labels, result.get("vocal_guard_only", False), "Grove")
    (app / "birdnet_species_profile.h").write_text(profile)
    payload, flash = package(model, labels)
    result.update(model_bytes=len(model), model_fnv1a=fnv1a(model),
                  flash_labels=flash, capture_sha256=digest(capture_elf.read_bytes()))
    files = [path for path in app.rglob("*") if path.is_file()
             and path.name != "birdnet_model_contract.h"]
    result["sources"] = {path.relative_to(app).as_posix(): digest(path.read_bytes())
                         for path in sorted(files)}
    result["id"] = digest(json.dumps(result, sort_keys=True).encode())
    header = ["// Generated by tools/grove_contract.py.", "#pragma once",
              "#define BIRDNET_LABELS_IN_FLASH 1", "namespace birdnet_contract {"]
    for name, value in (("Id", result["id"]), ("ModelSha256", result["model_sha256"]),
                        ("LabelsSha256", result["labels_sha256"])):
        section = ' __attribute__((used, section(".birdnet_contract")))' if name == "Id" else ""
        header.append(f'inline constexpr char k{name}[]{section} = "{value}";')
    for name, value in (("Classes", len(labels)), ("ModelBytes", len(model)),
                        ("ModelFnv", result["model_fnv1a"]), ("LabelBlobOffset", flash["offset"]),
                        ("LabelBlobBytes", flash["bytes"]), ("LabelBlobFnv", flash["fnv1a"])):
        header.append(f"inline constexpr unsigned k{name} = {value}u;")
    for name, tensor in result["tensors"].items():
        header.append(f'inline constexpr float k{name.title()}Scale = {tensor["scale"].hex()}f;')
        header.append(f'inline constexpr int k{name.title()}Zero = {tensor["zero_point"]};')
    (app / "birdnet_model_contract.h").write_text("\n".join(header + ["}", ""]))
    (bundle / "model-with-labels.bin").write_bytes(payload)
    (bundle / "deployment.json").write_text(json.dumps(result, indent=2) + "\n")


def seal(bundle):
    manifest = bundle / "deployment.json"
    result = json.loads(manifest.read_text())
    image = (bundle / "output.img").read_bytes()
    if not image or len(image) >= 0x200000 or result["id"].encode() + b"\0" not in image:
        raise ValueError("Image does not contain the expected deployment ID or fit the boot partition")
    result["image_sha256"] = digest(image)
    manifest.write_text(json.dumps(result, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    for action, names in (("prepare", ["models", "app", "capture_elf", "bundle"]),
                          ("seal", ["bundle"])):
        command = sub.add_parser(action)
        for name in names:
            command.add_argument(name, type=Path)
    args = vars(parser.parse_args())
    {"prepare": prepare, "seal": seal}[args.pop("action")](**args)
