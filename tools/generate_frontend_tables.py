"""Generate float32 frontend invariants from the selected frontend assets."""
import argparse
import hashlib
import math
from pathlib import Path
import re
import struct


def f32(value):
    return struct.unpack("f", struct.pack("f", value))[0]


def generate(directory: Path) -> str:
    header = (directory / "birdnet_frontend_assets.h").read_text()
    source = (directory / "birdnet_frontend_assets.cpp").read_text()
    sizes = [int(re.search(rf"kBranch{channel}FftSize = (\d+)", header)[1]) for channel in (1, 2)]
    body = re.search(r"kBranchPowerExponent\[2\]\s*=\s*\{([^}]+)", source)[1]
    exponents = [f32(float(value.strip().rstrip("f"))) for value in body.split(",") if value.strip()]
    digest = hashlib.sha256((header + source).encode()).hexdigest()
    arrays = {}
    for channel, size in enumerate(sizes, 1):
        window = []
        for i in range(size):
            angle = f32(f32(f32(2 * f32(math.pi)) * f32(i)) / size)
            window.append(f32(0.5 - f32(0.5 * f32(math.cos(angle)))))
        arrays[f"kWindow{channel}"] = window
    for channel, exponent in enumerate(exponents):
        arrays[f"kMantissa{channel}"] = [f32(math.pow(f32(0.5 + f32(0.5 * f32(i / 256))), exponent))
                                           for i in range(257)]
        arrays[f"kExp{channel}"] = [f32(math.pow(2, f32(exponent * i))) for i in range(-64, 65)]
    lines = ["// Generated by tools/generate_frontend_tables.py; do not edit.", "#pragma once",
             f"// Frontend assets SHA256: {digest}", "namespace birdnet_tables {"]
    for name, values in arrays.items():
        lines.append(f"alignas(32) inline constexpr float {name}[{len(values)}] = {{")
        for start in range(0, len(values), 6):
            # Hex literals round-trip the generated binary32 exactly.
            lines.append("  " + ", ".join(float(v).hex() + "f" for v in values[start:start + 6]) + ",")
        lines.append("};")
    lines.append("}  // namespace birdnet_tables\n")
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate(args.directory)
    output = args.directory / "birdnet_frontend_tables.h"
    if args.check:
        if not output.exists() or output.read_text() != result:
            raise SystemExit("Frontend invariant tables are stale")
    else:
        output.write_text(result)
